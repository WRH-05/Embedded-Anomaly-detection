#!/usr/bin/env python3
"""Train, quantize, evaluate, and export the Project P09 vibration classifier."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Iterator

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import tensorflow as tf
from sklearn.metrics import accuracy_score, confusion_matrix, f1_score
from sklearn.model_selection import GridSearchCV, StratifiedKFold, train_test_split
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVC


FEATURES = [
    "RMS_x",
    "RMS_y",
    "RMS_z",
    "peak_acc",
    "frequence_dominante",
    "energie",
]
LABEL_TO_ID = {
    "CALME": 0,
    "VIBRATION_NORMALE": 1,
    "VIBRATION_ANORMALE": 2,
}
LABELS = ["CALME", "VIBRATION_NORMALE", "VIBRATION_ANORMALE"]
RANDOM_STATE = 42


def load_dataset(csv_path: Path) -> tuple[pd.DataFrame, np.ndarray]:
    """Load and validate the feature rows used by both training and inference."""
    df = pd.read_csv(csv_path)
    required = [*FEATURES, "label"]
    missing = sorted(set(required) - set(df.columns))
    if missing:
        raise ValueError(f"{csv_path} is missing required columns: {', '.join(missing)}")

    df = df.loc[:, required].copy()
    for feature in FEATURES:
        df[feature] = pd.to_numeric(df[feature], errors="coerce")
    df["label"] = df["label"].astype("string").str.strip()
    df["frequence_dominante"] = df["frequence_dominante"].abs()
    df = df.dropna(subset=required)

    unknown_labels = sorted(set(df["label"]) - set(LABEL_TO_ID))
    if unknown_labels:
        raise ValueError(f"Unknown labels in {csv_path}: {', '.join(unknown_labels)}")
    if df.empty:
        raise ValueError(f"No valid training rows found in {csv_path}")

    y = df["label"].map(LABEL_TO_ID).to_numpy(dtype=np.int64)
    return df, y


def write_scaler_header(path: Path, scaler: StandardScaler) -> None:
    def cpp_float(value: float) -> str:
        formatted = f"{value:.9g}"
        if "." not in formatted and "e" not in formatted.lower():
            formatted += ".0"
        return formatted + "f"

    means = ", ".join(cpp_float(value) for value in scaler.mean_)
    stds = ", ".join(cpp_float(value) for value in scaler.scale_)
    content = (
        "#pragma once\n"
        "// Generated by train_and_export.py; StandardScaler population statistics.\n"
        f"const float SCALER_MEAN[6] = {{{means}}};\n"
        f"const float SCALER_STD[6] = {{{stds}}};\n"
    )
    path.write_text(content, encoding="utf-8")


def write_model_header(path: Path, model_bytes: bytes) -> None:
    rows = [
        "  " + ", ".join(f"0x{value:02x}" for value in model_bytes[index : index + 12])
        for index in range(0, len(model_bytes), 12)
    ]
    content = (
        "#pragma once\n"
        "#include <stdint.h>\n\n"
        f"const unsigned int g_model_len = {len(model_bytes)};\n"
        "const unsigned char g_model[] __attribute__((aligned(16))) = {\n"
        + ",\n".join(rows)
        + "\n};\n"
    )
    path.write_text(content, encoding="utf-8")


def representative_dataset(
    X_train_scaled: np.ndarray,
) -> Iterator[list[np.ndarray]]:
    for sample in X_train_scaled:
        yield [sample.reshape(1, len(FEATURES)).astype(np.float32)]


def evaluate_int8_model(
    model_bytes: bytes, X_test_scaled: np.ndarray
) -> tuple[np.ndarray, np.ndarray]:
    interpreter = tf.lite.Interpreter(model_content=model_bytes)
    interpreter.allocate_tensors()
    input_detail = interpreter.get_input_details()[0]
    output_detail = interpreter.get_output_details()[0]
    input_scale, input_zero_point = input_detail["quantization"]
    output_scale, output_zero_point = output_detail["quantization"]
    if input_scale <= 0 or output_scale <= 0:
        raise RuntimeError("The converted model has invalid int8 quantization scales")

    predictions: list[int] = []
    probabilities: list[np.ndarray] = []
    for sample in X_test_scaled:
        quantized = np.clip(
            np.rint(sample / input_scale) + input_zero_point, -128, 127
        ).astype(np.int8)
        interpreter.set_tensor(input_detail["index"], quantized.reshape(1, -1))
        interpreter.invoke()
        output_int8 = interpreter.get_tensor(output_detail["index"])[0]
        output_probabilities = (
            output_int8.astype(np.float32) - output_zero_point
        ) * output_scale
        probabilities.append(output_probabilities)
        predictions.append(int(np.argmax(output_probabilities)))

    return np.asarray(predictions, dtype=np.int64), np.asarray(probabilities)


def save_confusion_plot(
    path: Path,
    y_test: np.ndarray,
    predictions: list[np.ndarray],
    titles: list[str],
) -> None:
    fig, axes = plt.subplots(1, len(predictions), figsize=(15, 4.8))
    for axis, predicted, title in zip(axes, predictions, titles):
        matrix = confusion_matrix(y_test, predicted, labels=[0, 1, 2])
        image = axis.imshow(matrix, cmap="Blues")
        axis.set_title(title)
        axis.set_xlabel("Predicted class")
        axis.set_ylabel("True class")
        axis.set_xticks(range(3), LABELS, rotation=25, ha="right")
        axis.set_yticks(range(3), LABELS)
        threshold = matrix.max() / 2 if matrix.size else 0
        for row in range(matrix.shape[0]):
            for column in range(matrix.shape[1]):
                axis.text(
                    column,
                    row,
                    str(matrix[row, column]),
                    ha="center",
                    va="center",
                    color="white" if matrix[row, column] > threshold else "black",
                )
        fig.colorbar(image, ax=axis, fraction=0.046, pad=0.04)
    fig.tight_layout()
    fig.savefig(path, dpi=300)
    plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--csv",
        type=Path,
        default=Path(__file__).resolve().with_name("dataset_P09_v2.csv"),
        help="Input dataset CSV (default: dataset_P09_v2.csv beside this script)",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path(__file__).resolve().parent,
        help="Directory for generated models, headers, plots, and metrics",
    )
    args = parser.parse_args()
    output_dir = args.output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    df, y = load_dataset(args.csv)
    X = df[FEATURES].to_numpy(dtype=np.float32)
    X_train, X_holdout, y_train, y_holdout = train_test_split(
        X,
        y,
        test_size=0.30,
        stratify=y,
        random_state=RANDOM_STATE,
    )
    X_val, X_test, y_val, y_test = train_test_split(
        X_holdout,
        y_holdout,
        test_size=0.50,
        stratify=y_holdout,
        random_state=RANDOM_STATE,
    )

    scaler = StandardScaler()
    X_train_scaled = scaler.fit_transform(X_train).astype(np.float32)
    X_val_scaled = scaler.transform(X_val).astype(np.float32)
    X_test_scaled = scaler.transform(X_test).astype(np.float32)
    write_scaler_header(output_dir / "scaler_params.h", scaler)

    svm_pipeline = Pipeline(
        [("scaler", StandardScaler()), ("svc", SVC(kernel="rbf"))]
    )
    svm_search = GridSearchCV(
        svm_pipeline,
        param_grid={
            "svc__C": [0.1, 1.0, 10.0, 100.0],
            "svc__gamma": ["scale", 0.001, 0.01, 0.1, 1.0],
        },
        scoring="f1_macro",
        cv=StratifiedKFold(n_splits=5, shuffle=True, random_state=RANDOM_STATE),
        n_jobs=1,
    )
    svm_search.fit(X_train, y_train)
    svm_predictions = svm_search.predict(X_test)
    svm_accuracy = accuracy_score(y_test, svm_predictions)
    svm_macro_f1 = f1_score(y_test, svm_predictions, average="macro")

    tf.keras.utils.set_random_seed(RANDOM_STATE)
    mlp = tf.keras.Sequential(
        [
            tf.keras.layers.Input(shape=(len(FEATURES),)),
            tf.keras.layers.Dense(16, activation="relu"),
            tf.keras.layers.Dense(8, activation="relu"),
            tf.keras.layers.Dense(3, activation="softmax"),
        ]
    )
    mlp.compile(
        optimizer=tf.keras.optimizers.Adam(learning_rate=0.005),
        loss="sparse_categorical_crossentropy",
        metrics=["accuracy"],
    )
    early_stopping = tf.keras.callbacks.EarlyStopping(
        monitor="val_loss", patience=15, restore_best_weights=True
    )
    mlp.fit(
        X_train_scaled,
        y_train,
        validation_data=(X_val_scaled, y_val),
        epochs=500,
        batch_size=16,
        callbacks=[early_stopping],
        verbose=0,
    )
    float_probabilities = mlp.predict(X_test_scaled, verbose=0)
    float_predictions = np.argmax(float_probabilities, axis=1)
    float_accuracy = accuracy_score(y_test, float_predictions)
    float_macro_f1 = f1_score(y_test, float_predictions, average="macro")

    float_converter = tf.lite.TFLiteConverter.from_keras_model(mlp)
    float_model_bytes = float_converter.convert()
    converter = tf.lite.TFLiteConverter.from_keras_model(mlp)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.representative_dataset = lambda: representative_dataset(X_train_scaled)
    converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    converter.inference_input_type = tf.int8
    converter.inference_output_type = tf.int8
    int8_model_bytes = converter.convert()

    int8_model_path = output_dir / "model_vibration_int8.tflite"
    int8_model_path.write_bytes(int8_model_bytes)
    write_model_header(output_dir / "model_data.h", int8_model_bytes)

    int8_predictions, _ = evaluate_int8_model(int8_model_bytes, X_test_scaled)
    int8_accuracy = accuracy_score(y_test, int8_predictions)
    int8_macro_f1 = f1_score(y_test, int8_predictions, average="macro")
    accuracy_loss = float_accuracy - int8_accuracy

    plot_df = df.copy()
    plot_df["label"] = plot_df["label"].astype("category")
    fig, axis = plt.subplots(figsize=(8, 5.5))
    for label in LABEL_TO_ID:
        subset = plot_df[plot_df["label"] == label]
        axis.scatter(
            subset["RMS_z"],
            subset["energie"],
            label=label,
            alpha=0.75,
            s=28,
        )
    axis.set_yscale("log")
    axis.set_xlabel("RMS_z (g)")
    axis.set_ylabel("Energie (g²)")
    axis.set_title("RMS_z vs énergie par classe")
    axis.grid(True, which="both", linestyle=":", alpha=0.45)
    axis.legend()
    fig.tight_layout()
    fig.savefig(output_dir / "plot1_rms_vs_energie.png", dpi=300)
    plt.close(fig)

    save_confusion_plot(
        output_dir / "plot2_confusion_matrices.png",
        y_test,
        [svm_predictions, float_predictions, int8_predictions],
        ["SVM RBF", "MLP float32", "MLP int8 TFLite"],
    )

    metrics = {
        "test_rows": int(len(y_test)),
        "class_labels": LABELS,
        "svm": {
            "accuracy": float(svm_accuracy),
            "macro_f1": float(svm_macro_f1),
            "best_params": svm_search.best_params_,
        },
        "float32_accuracy": float(float_accuracy),
        "float32_macro_f1": float(float_macro_f1),
        "int8_accuracy": float(int8_accuracy),
        "int8_macro_f1": float(int8_macro_f1),
        "accuracy_loss_percentage_points": float(accuracy_loss * 100.0),
        "float32_model_bytes": len(float_model_bytes),
        "int8_model_bytes": len(int8_model_bytes),
        "compression_ratio_pct": float(
            100.0 * (1.0 - len(int8_model_bytes) / len(float_model_bytes))
        ),
    }
    (output_dir / "table_metrics_summary.json").write_text(
        json.dumps(metrics, indent=2) + "\n", encoding="utf-8"
    )

    print(f"Rows: train={len(y_train)}, validation={len(y_val)}, test={len(y_test)}")
    print(f"SVM test accuracy={svm_accuracy:.4f}, macro-F1={svm_macro_f1:.4f}")
    print(f"MLP float32 accuracy={float_accuracy:.4f}, macro-F1={float_macro_f1:.4f}")
    print(f"MLP int8 accuracy={int8_accuracy:.4f}, macro-F1={int8_macro_f1:.4f}")
    print(f"Float32 -> int8 accuracy loss: {accuracy_loss * 100.0:.2f} percentage points")
    print(
        "Artifacts saved to "
        f"{output_dir}; float32 TFLite={len(float_model_bytes)} bytes, "
        f"int8 TFLite={len(int8_model_bytes)} bytes"
    )
    if accuracy_loss > 0.03:
        raise RuntimeError(
            "int8 accuracy degradation exceeds the allowed 3.0 percentage points"
        )


if __name__ == "__main__":
    main()
